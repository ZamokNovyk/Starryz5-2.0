for filepath in locale_files:
    filename = os.path.basename(filepath)
    lang_code = filename.replace('.ts', '')
    
    with open(filepath, 'r', encoding='utf-8') as f:
        content = f.read()

    # Find the closing brace of dictionary
    last_brace_idx = content.rfind('};')
    if last_brace_idx == -1:
        continue
    
    extra_entries = []
    for k, trans_map in new_keys.items():
        if f"'{k}':" not in content and f'"{k}":' not in content:
            val = trans_map.get(lang_code, trans_map.get('en', ''))
            val_escaped = val.replace("'", "\\'")
            extra_entries.append(f"  '{k}': '{val_escaped}',")

    if extra_entries:
        inserted_text = "\n" + "\n".join(extra_entries) + "\n"
        new_content = content[:last_brace_idx] + inserted_text + content[last_brace_idx:]
        with open(filepath, 'w', encoding='utf-8') as f:
            f.write(new_content)
        print(f"Updated {lang_code}.ts with {len(extra_entries)} keys")

print("All locale dictionaries updated successfully!")

