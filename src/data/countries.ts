/**
 * Obtiene la URL de la bandera en alta resolución desde el CDN oficial de flagcdn.com
 * @param code Código ISO alpha-2 en minúsculas (ej: 'pe', 'mx')
 * @param size Ancho deseado ('w20', 'w40', 'w80', 'w160')
 */
export function getFlagUrl(code: string, size: 'w20' | 'w40' | 'w80' | 'w160' = 'w40'): string {
  if (!code) return '';
  return `https://flagcdn.com/${size}/${code.toLowerCase()}.png`;
}

/**
 * Busca un país por su código ISO o por su nombre
 */
export function findCountry(codeOrName: string): Country | undefined {
  if (!codeOrName) return undefined;
  const clean = codeOrName.trim().toLowerCase();
  return COUNTRIES.find(
    c => c.code.toLowerCase() === clean || c.name.toLowerCase() === clean
  );
}
